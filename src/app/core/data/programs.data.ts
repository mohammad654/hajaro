// ---------- Authoring helpers (keep schedules concise and consistent) ----------
const REST = { heavy: 180, compound: 120, accessory: 90, isolation: 60 } as const;

const ex = (
  exerciseId: string,
  sets: string,
  reps: string,
  restSeconds: number,
  notes?: string,
): WorkoutExercise => ({
  exerciseId,
  sets,
  reps,
  restSeconds,
  ...(notes ? { notes } : {}),
});

const day = (
  id: string,
  label: string,
  focus: string,
  exercises: readonly WorkoutExercise[],
): WorkoutDay => ({
  id,
  label,
  focus,
  isRestDay: false,
  exercises,
});

const rest = (
  id: string,
  label: string,
  focus = $localize`Rest and recovery: walking or light mobility`,
): WorkoutDay => ({
  id,
  label,
  focus,
  isRestDay: true,
  exercises: [],
});

